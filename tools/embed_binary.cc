// Build-time helper: embeds a binary file as a C++ byte array.
//
// Usage:
//   embed_binary <output> <name>=<file>

#include <cstdio>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>

namespace
{

bool readFile(const std::string& path, std::string& out)
{
    std::ifstream in(path, std::ios::binary);
    if (!in)
        return false;
    out.assign(std::istreambuf_iterator<char>(in),
               std::istreambuf_iterator<char>());
    return true;
}

} //namespace

int main(int argc, char** argv)
{
    if (argc != 3)
    {
        std::cerr << "usage: embed_binary <output> <name>=<file>\n";
        return 1;
    }

    std::string arg = argv[2];
    std::size_t eq = arg.find('=');
    if (eq == std::string::npos || eq == 0 || eq + 1 >= arg.size())
    {
        std::cerr << "invalid argument: " << arg << "\n";
        return 1;
    }

    std::string name = arg.substr(0, eq);
    std::string file = arg.substr(eq + 1);

    std::string data;
    if (!readFile(file, data))
    {
        std::cerr << "cannot read " << file << "\n";
        return 1;
    }

    std::ofstream out(argv[1], std::ios::binary | std::ios::trunc);
    if (!out)
    {
        std::cerr << "cannot write " << argv[1] << "\n";
        return 1;
    }

    out << "// Generated by tools/embed_binary.cc. Do not edit.\n";
    out << "#pragma once\n\n";
    out << "#include <cstddef>\n\n";
    out << "namespace sdlagent::icon\n{\n\n";
    out << "inline constexpr unsigned char " << name << "[] = {\n";

    for (std::size_t i = 0; i < data.size(); ++i)
    {
        if (i % 16 == 0)
            out << "    ";
        char buf[8];
        std::snprintf(buf, sizeof(buf), "0x%02X",
                      (unsigned int)(unsigned char)data[i]);
        out << buf;
        if (i + 1 < data.size())
            out << ", ";
        if (i % 16 == 15)
            out << "\n";
    }

    out << "\n};\n\n";
    out << "inline constexpr std::size_t " << name << "Size = "
        << data.size() << ";\n\n";
    out << "} //namespace sdlagent::icon\n";
    return 0;
}
