// Build-time helper: embeds Markdown/text assets into a generated header.
//
// Usage:
//   embed_prompts <output> <name>=<file> [<name>=<file> ...]

#include <fstream>
#include <iostream>
#include <iterator>
#include <string>

namespace
{

bool readFile(const std::string& path, std::string& out)
{
    std::ifstream in(path, std::ios::binary);
    if (!in)
        return false;
    out.assign((std::istreambuf_iterator<char>(in)),
               std::istreambuf_iterator<char>());
    return true;
}

} //namespace

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        std::cerr << "usage: embed_prompts <output> <name>=<file> ...\n";
        return 1;
    }

    const std::string outPath = argv[1];
    const std::string delimiter = "SDLPROMPT";

    std::string text;
    text += "// Generated by tools/embed_prompts.cc. Do not edit.\n";
    text += "#pragma once\n\n";
    text += "namespace sdlagent::prompt::defaults\n{\n";

    for (int i = 2; i < argc; ++i)
    {
        std::string arg = argv[i];
        std::size_t eq = arg.find('=');
        if (eq == std::string::npos || eq == 0 || eq + 1 >= arg.size())
        {
            std::cerr << "invalid argument: " << arg << "\n";
            return 1;
        }

        std::string name = arg.substr(0, eq);
        std::string file = arg.substr(eq + 1);

        std::string content;
        if (!readFile(file, content))
        {
            std::cerr << "cannot read " << file << "\n";
            return 1;
        }

        if (content.find(")" + delimiter + "\"") != std::string::npos)
        {
            std::cerr << "file contains the raw-string delimiter: " << file
                      << "\n";
            return 1;
        }

        text += "\ninline constexpr const char ";
        text += name;
        text += "[] = R\"";
        text += delimiter;
        text += "(";
        text += content;
        text += ")";
        text += delimiter;
        text += "\";\n";
    }

    text += "\n} //namespace sdlagent::prompt::defaults\n";

    std::ofstream out(outPath, std::ios::binary | std::ios::trunc);
    if (!out)
    {
        std::cerr << "cannot write " << outPath << "\n";
        return 1;
    }

    out.write(text.data(), (std::streamsize)text.size());
    if (!out)
    {
        std::cerr << "write failed: " << outPath << "\n";
        return 1;
    }
    return 0;
}
